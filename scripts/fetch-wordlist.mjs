/* Vendors the BIP-39 English wordlist so the app has no network dependency
   at runtime. Re-run only if the list ever needs refreshing. */
import fs from 'fs';

const res = await fetch('https://raw.githubusercontent.com/bitcoin/bips/master/bip-0039/english.txt');
if (!res.ok) throw new Error('HTTP ' + res.status);
const words = (await res.text()).split('\n').map((w) => w.trim()).filter(Boolean);
if (words.length !== 2048) throw new Error('expected 2048 words, got ' + words.length);

fs.writeFileSync(
  'server/lib/wordlist.js',
  '/* BIP-39 English wordlist (2048 words), from bitcoin/bips. Generated by scripts/fetch-wordlist.mjs. */\n' +
    'export const WORDLIST = ' + JSON.stringify(words) + ';\n'
);
console.log('words:', words.length, '| first:', words[0], '| last:', words.at(-1));
const shot = ['artist','alcohol','daring','beauty','business','argue','cruise','depart','caution','debris','deal','amused'];
console.log('reference-screenshot words all present:', shot.every((w) => words.includes(w)));
